import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const csvPath = path.join(root, 'data', 'raw', 'laws-and-acts-of-india', 'indian_laws_and_acts_v2.csv');
const outputPath = path.join(root, 'src', 'data', 'lawsAndActs.ts');

function parseCsv(text) {
  const rows = [];
  let cell = '';
  let row = [];
  let inQuotes = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (char === '"' && inQuotes && next === '"') {
      cell += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      inQuotes = !inQuotes;
      continue;
    }

    if (char === ',' && !inQuotes) {
      row.push(cell);
      cell = '';
      continue;
    }

    if ((char === '\n' || char === '\r') && !inQuotes) {
      if (char === '\r' && next === '\n') index += 1;
      row.push(cell);
      if (row.some((value) => value.trim().length > 0)) rows.push(row);
      row = [];
      cell = '';
      continue;
    }

    cell += char;
  }

  if (cell.length > 0 || row.length > 0) {
    row.push(cell);
    rows.push(row);
  }

  return rows;
}

function normalise(value) {
  return String(value ?? '').replace(/\s+/g, ' ').trim();
}

function toRecord(headers, row, index) {
  const values = Object.fromEntries(headers.map((header, cellIndex) => [header, normalise(row[cellIndex])]));
  return {
    id: `law-${index + 1}`,
    title: values.title || 'Untitled law or act',
    source: values.source || 'Unknown',
    place: values.place || 'Unknown',
    publishedDate: values.published_date || '',
    commencementDate: values.commencement_date || '',
    url: values.url || '',
  };
}

if (!fs.existsSync(csvPath)) {
  throw new Error(`Dataset CSV not found at ${csvPath}`);
}

const csv = fs.readFileSync(csvPath, 'utf8');
const [headerRow, ...dataRows] = parseCsv(csv);
const headers = headerRow.map((header) => normalise(header));
const seen = new Set();
const records = [];

dataRows.forEach((row, index) => {
  const record = toRecord(headers, row, index);
  const key = `${record.title.toLowerCase()}|${record.url.toLowerCase()}`;
  if (!seen.has(key)) {
    seen.add(key);
    records.push(record);
  }
});

records.sort((first, second) => first.title.localeCompare(second.title));

const source = `// Generated by scripts/prepare-law-dataset.mjs from Kaggle laws-and-acts-of-india.
// Source: https://www.kaggle.com/datasets/kausthubkannan/laws-and-acts-of-india

export interface LawDatasetRecord {
  id: string;
  title: string;
  source: string;
  place: string;
  publishedDate: string;
  commencementDate: string;
  url: string;
}

export const lawDatasetSource = {
  name: 'Laws and Acts of India',
  provider: 'Kaggle / kausthubkannan',
  url: 'https://www.kaggle.com/datasets/kausthubkannan/laws-and-acts-of-india',
  generatedAt: '${new Date().toISOString()}',
  records: ${records.length},
} as const;

export const indianLawDataset: LawDatasetRecord[] = ${JSON.stringify(records, null, 2)};
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source, 'utf8');

console.log(`Generated ${records.length} law records at ${outputPath}`);
